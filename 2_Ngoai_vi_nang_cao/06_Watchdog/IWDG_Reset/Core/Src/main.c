/* Tra ve 1 khi vua nhan nut BTN (PB12 keo len, nhan = muc thap), co chong doi phim */
static uint8_t Button_WasPressed(void)
{
  static GPIO_PinState stable = GPIO_PIN_SET;
  static uint32_t t_change = 0;
  GPIO_PinState now = HAL_GPIO_ReadPin(BTN_GPIO_Port, BTN_Pin);
  if (now != stable && (HAL_GetTick() - t_change) > 30U)
  {
    t_change = HAL_GetTick();
    stable = now;
    if (now == GPIO_PIN_RESET) return 1;
  }
  return 0;
}

static void Print_ResetCause(void)
{
  printf("Nguyen nhan reset:");
  if (__HAL_RCC_GET_FLAG(RCC_FLAG_IWDGRST)) printf(" [IWDG - watchdog doc lap]");
  if (__HAL_RCC_GET_FLAG(RCC_FLAG_WWDGRST)) printf(" [WWDG]");
  if (__HAL_RCC_GET_FLAG(RCC_FLAG_SFTRST))  printf(" [Software]");
  if (__HAL_RCC_GET_FLAG(RCC_FLAG_PORRST))  printf(" [Bat nguon]");
  else if (__HAL_RCC_GET_FLAG(RCC_FLAG_PINRST)) printf(" [Chan NRST / nut RESET]");
  if (__HAL_RCC_GET_FLAG(RCC_FLAG_LPWRRST)) printf(" [Low-power]");
  printf("\r\n");
  __HAL_RCC_CLEAR_RESET_FLAGS();          /* xoa de lan sau doc dung */
}
