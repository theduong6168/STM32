/* Tra ve 1 khi vua nhan nut BTN (PB12 keo len, nhan = muc thap), co chong doi phim */
static uint8_t Button_WasPressed(void)
{
  static GPIO_PinState stable = GPIO_PIN_SET;
  static uint32_t t_change = 0;
  GPIO_PinState now = HAL_GPIO_ReadPin(BTN_GPIO_Port, BTN_Pin);
  if (now != stable && (HAL_GetTick() - t_change) > 30U)
  {
    t_change = HAL_GetTick();
    stable = now;
    if (now == GPIO_PIN_RESET) return 1;
  }
  return 0;
}

#define CS_LOW()   HAL_GPIO_WritePin(CS_GPIO_Port, CS_Pin, GPIO_PIN_RESET)
#define CS_HIGH()  HAL_GPIO_WritePin(CS_GPIO_Port, CS_Pin, GPIO_PIN_SET)

/* Gui va nhan dong thoi n byte (SPI luon full-duplex) */
static HAL_StatusTypeDef SPI_Transfer(const uint8_t *tx, uint8_t *rx, uint16_t n)
{
  CS_LOW();
  HAL_StatusTypeDef st = HAL_SPI_TransmitReceive(&hspi1, (uint8_t *)tx, rx, n, 100);
  CS_HIGH();
  return st;
}

static void Print_Hex(const char *label, const uint8_t *b, uint16_t n)
{
  printf("%s", label);
  for (uint16_t i = 0; i < n; i++) printf("%02X ", b[i]);
  printf("\r\n");
}

#if TEST_W25QXX
static void W25Q_Test(void)
{
  uint8_t tx[4 + LEN] = { 0x9F, 0, 0, 0 }, rx[4 + LEN];
  SPI_Transfer(tx, rx, 4);                                 /* 0x9F: JEDEC ID */
  printf("JEDEC ID: Manufacturer=0x%02X Type=0x%02X Capacity=0x%02X %s\r\n",
         rx[1], rx[2], rx[3], rx[1] == 0xEF ? "(Winbond)" : "");
  tx[0] = 0x03; tx[1] = tx[2] = tx[3] = 0;                 /* 0x03: Read Data tu dia chi 0 */
  for (uint16_t i = 4; i < sizeof(tx); i++) tx[i] = 0xFF;
  SPI_Transfer(tx, rx, sizeof(tx));
  Print_Hex("Data @0x000000: ", &rx[4], LEN);
}
#else
static void Loopback_Test(uint8_t seed)
{
  uint8_t tx[LEN], rx[LEN] = {0}, err = 0;
  for (uint8_t i = 0; i < LEN; i++) tx[i] = (uint8_t)(seed + i * 17);
  if (SPI_Transfer(tx, rx, LEN) != HAL_OK) { printf("HAL SPI loi!\r\n"); return; }
  for (uint8_t i = 0; i < LEN; i++) if (tx[i] != rx[i]) err++;
  Print_Hex("TX: ", tx, LEN);
  Print_Hex("RX: ", rx, LEN);
  printf("=> %s (%u byte sai)\r\n\r\n", err ? "FAIL - kiem tra day noi PA6-PA7" : "PASS", err);
  LED_SET(err == 0);
}
#endif
