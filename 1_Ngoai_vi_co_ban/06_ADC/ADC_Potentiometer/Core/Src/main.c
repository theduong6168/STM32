/* Doc ADC (polling) va lay trung binh n mau de giam nhieu */
static uint32_t ADC_ReadAvg(uint8_t n)
{
  uint32_t sum = 0;
  for (uint8_t i = 0; i < n; i++)
  {
    HAL_ADC_Start(&hadc1);
    if (HAL_ADC_PollForConversion(&hadc1, 10) == HAL_OK)
    {
      sum += HAL_ADC_GetValue(&hadc1);
    }
  }
  HAL_ADC_Stop(&hadc1);
  return sum / n;
}
