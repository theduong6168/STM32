  LedMode_t mode = MODE_RIGHT;
  uint8_t   pos = 0, mask = 0;
  uint32_t  t_step = 0, t_heartbeat = 0;
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

